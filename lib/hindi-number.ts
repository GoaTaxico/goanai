function under1000(value: number) {
  if (value < 100) return BELOW_100[value] ?? "";
  const hundreds = Math.floor(value / 100);
  const rest = value % 100;
  const head = hundreds === 1 ? "एक सौ" : `${BELOW_100[hundreds]} सौ`;
  return rest ? `${head} ${BELOW_100[rest]}` : head;
}

export function hindiNumber(value: number) {
  if (!Number.isInteger(value) || value < 0 || value > 9_999_999_999) return null;
  if (value === 0) return "शून्य";

  const parts: string[] = [];
  const crore = Math.floor(value / 10_000_000);
  let rest = value % 10_000_000;
  const lakh = Math.floor(rest / 100_000);
  rest %= 100_000;
  const thousand = Math.floor(rest / 1000);
  rest %= 1000;

  if (crore) parts.push(`${under1000(crore)} करोड़`);
  if (lakh) parts.push(`${BELOW_100[lakh]} लाख`);
  if (thousand) parts.push(`${BELOW_100[thousand]} हज़ार`);
  if (rest) parts.push(under1000(rest));
  return parts.join(" ");
}
